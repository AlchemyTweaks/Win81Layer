namespace Win81Layer;

// One entry of HKCU\...\Explorer\Taskband\Favorites, in native taskbar order. Read-only view: the launcher never
// writes the native pin store (Explorer owns it and rewrites it; programmatic pinning is unsupported).
internal sealed class NativeTaskbarPin
{
	public int Order { get; init; }

	// "lnk": a shortcut in %APPDATA%\Microsoft\Internet Explorer\Quick Launch\User Pinned\TaskBar (LnkName).
	// "packaged": an AppsFolder item (no .lnk at all; identity is the AUMID). "other": unknown root, ignored.
	public string Kind { get; init; } = "other";

	public string? LnkName { get; init; }

	// 0xBEEF001D: the AppUserModelID Explorer resolved for the pin. Explicit ("Chrome", "notion.id",
	// "Pkg_xxx!App"), implicit exe-derived ("C:\\...\\Viber.exe", "{KnownFolderGuid}\\rel\\app.exe") or
	// "Microsoft.AutoGenerated.{GUID}".
	public string? Aumid { get; init; }

	// 0xBEEF001E: UserPinned, SystemPinned, OOBEPinned, CloudPinned, RestorePinned, PlaceholderPinned,
	// ProgrammablePlaceholder, ProgrammableRestored. Only UserPinned means the user did it.
	public string? Origin { get; init; }

	// 0xBEEF002B FILETIME: when the pin was made (matches the .lnk creation time to ~10 ms; packaged pins have it
	// too). Used for the first-run catch-up.
	public DateTime? PinnedUtc { get; init; }

	public string? PackageFamily { get; init; }

	public override string ToString() => $"#{Order} {Kind} {LnkName ?? Aumid} origin={Origin} pinned={PinnedUtc:u} aumid={Aumid}";
}

// Reader for the native taskbar's real pin list. The TaskBar .lnk folder alone is not authoritative: packaged pins
// have no .lnk, and installers drop .lnk files there that were never pinned.
internal static class NativeTaskbarFavorites
{
	public const string KeyPath = "Software\\Microsoft\\Windows\\CurrentVersion\\Explorer\\Taskband";

	private static readonly Guid UserPinnedFolder = new Guid("1f3427c8-5c10-4210-aa03-2ee45287d668");

	private static readonly Guid AppsFolder = new Guid("4234d49b-0245-4df3-b780-3893943456e1");

	private static readonly Guid FmtidAppUserModel = new Guid("9f4c2855-9f79-4b39-a8d0-e1d42de1d5f3");

	// Reads Favorites (+ FavoritesChanges for logging) with KEY_READ only. Null when the key or value is missing or
	// does not parse: the caller treats that as "unknown", never as "no pins".
	public static List<NativeTaskbarPin>? Read(string keyPath, out int favoritesChanges, out string? error)
	{
		favoritesChanges = -1;
		error = null;
		try
		{
			using RegistryKey? key = Registry.CurrentUser.OpenSubKey(keyPath, writable: false);
			if (key == null)
			{
				error = "Taskband key missing";
				return null;
			}
			if (key.GetValue("Favorites") is not byte[] blob)
			{
				error = "Favorites value missing";
				return null;
			}
			if (key.GetValue("FavoritesChanges") is int changes)
			{
				favoritesChanges = changes;
			}
			List<NativeTaskbarPin>? pins = Parse(blob);
			if (pins == null)
			{
				error = $"Favorites did not parse ({blob.Length} bytes)";
			}
			return pins;
		}
		catch (Exception ex)
		{
			error = ex.GetType().Name + ": " + ex.Message;
			return null;
		}
	}

	// Favorites (FavoritesVersion 3): repeat { BYTE 0x00, DWORD cb, ITEMIDLIST[cb] } then BYTE 0xFF.
	public static List<NativeTaskbarPin>? Parse(byte[] blob)
	{
		List<NativeTaskbarPin> pins = new List<NativeTaskbarPin>();
		int o = 0;
		while (o < blob.Length && blob[o] != 0xFF)
		{
			if (blob[o] != 0x00 || o + 5 > blob.Length)
			{
				return null;
			}
			int cb = BitConverter.ToInt32(blob, o + 1);
			if (cb < 2 || o + 5 + cb > blob.Length)
			{
				return null;
			}
			pins.Add(ParseEntry(new ReadOnlySpan<byte>(blob, o + 5, cb), pins.Count));
			o += 5 + cb;
		}
		if (o >= blob.Length)
		{
			return null;   // no 0xFF terminator: truncated or not this format
		}
		return pins;
	}

	private static NativeTaskbarPin ParseEntry(ReadOnlySpan<byte> idl, int order)
	{
		Guid root = Guid.Empty;
		ReadOnlySpan<byte> last = default;
		int o = 0;
		while (o + 2 <= idl.Length)
		{
			int cb = BitConverter.ToUInt16(idl.Slice(o, 2));
			if (cb == 0 || o + cb > idl.Length)
			{
				break;
			}
			ReadOnlySpan<byte> item = idl.Slice(o, cb);
			if (o == 0 && cb >= 20 && item[2] == 0x1F)
			{
				root = new Guid(item.Slice(4, 16));
			}
			last = item;
			o += cb;
		}
		string? longName = null, aumid = null, origin = null, family = null;
		DateTime? pinned = null;
		bool isFile = last.Length > 3 && (last[2] & 0x70) == 0x30 && (last[2] & 0x01) == 0;
		if (last.Length > 10 && last[2] == 0x00 && last.Slice(6, 4).SequenceEqual("APPS"u8))
		{
			int sps = last.IndexOf("1SPS"u8);
			if (sps >= 4)
			{
				ReadAppUserModelProps(last.Slice(sps - 4), ref aumid, ref family);
			}
		}
		int ext = FirstExtensionBlock(last);
		while (ext > 0 && ext + 8 <= last.Length)
		{
			int size = BitConverter.ToUInt16(last.Slice(ext, 2));
			ushort version = BitConverter.ToUInt16(last.Slice(ext + 2, 2));
			uint sig = BitConverter.ToUInt32(last.Slice(ext + 4, 4));
			if (size < 8 || ext + size > last.Length || (sig & 0xFFFF0000u) != 0xBEEF0000u)
			{
				break;
			}
			ReadOnlySpan<byte> blk = last.Slice(ext, size);
			switch (sig)
			{
				case 0xBEEF0004u:
					longName = Utf16Z(blk, LongNameOffset(version), blk.Length - 2);
					break;
				case 0xBEEF001Du:
					aumid = Utf16Z(blk, 10, blk.Length);
					break;
				case 0xBEEF001Eu:
					origin = Utf16Z(blk, 10, blk.Length);
					break;
				case 0xBEEF002Bu:
					if (size >= 16)
					{
						long ft = BitConverter.ToInt64(blk.Slice(8, 8));
						pinned = ft > 0 ? DateTime.FromFileTimeUtc(ft) : null;
					}
					break;
			}
			ext += size;
		}
		string kind = root == UserPinnedFolder && isFile && longName != null ? "lnk" : root == AppsFolder && aumid != null ? "packaged" : "other";
		return new NativeTaskbarPin
		{
			Order = order,
			Kind = kind,
			LnkName = kind == "lnk" ? longName : null,
			Aumid = aumid,
			Origin = origin,
			PinnedUtc = pinned,
			PackageFamily = family
		};
	}

	// BEEF0004 v9 (Win8+): header 8, ctime 4, atime 4, id 2, (v7+) 2+8+8, (v3+) 2, (v9+) 4, (v8+) 4, long name.
	internal static int LongNameOffset(ushort version)
	{
		int off = 18;
		if (version >= 7) off += 18;
		if (version >= 3) off += 2;
		if (version >= 9) off += 4;
		if (version >= 8) off += 4;
		return off;
	}

	private static int FirstExtensionBlock(ReadOnlySpan<byte> item)
	{
		if (item.Length < 12)
		{
			return -1;
		}
		int hint = BitConverter.ToUInt16(item.Slice(item.Length - 2, 2));
		if (hint > 3 && hint + 8 <= item.Length && item[hint + 6] == 0xEF && item[hint + 7] == 0xBE)
		{
			return hint;
		}
		for (int i = 4; i + 8 <= item.Length; i++)
		{
			int size = BitConverter.ToUInt16(item.Slice(i, 2));
			if (item[i + 6] == 0xEF && item[i + 7] == 0xBE && size >= 8 && i + size <= item.Length)
			{
				return i;
			}
		}
		return -1;
	}

	// Serialized property storage: { DWORD size, "1SPS", FMTID, { DWORD vsize, DWORD pid, BYTE 0, VARTYPE, ... }* }*
	private static void ReadAppUserModelProps(ReadOnlySpan<byte> b, ref string? aumid, ref string? family)
	{
		int o = 0;
		while (o + 24 <= b.Length)
		{
			int ssize = BitConverter.ToInt32(b.Slice(o, 4));
			if (ssize <= 0 || o + ssize > b.Length || !b.Slice(o + 4, 4).SequenceEqual("1SPS"u8))
			{
				return;
			}
			bool aum = new Guid(b.Slice(o + 8, 16)) == FmtidAppUserModel;
			int p = o + 24;
			while (aum && p + 13 <= o + ssize)
			{
				int vsize = BitConverter.ToInt32(b.Slice(p, 4));
				if (vsize <= 0)
				{
					break;
				}
				int pid = BitConverter.ToInt32(b.Slice(p + 4, 4));
				ushort vt = BitConverter.ToUInt16(b.Slice(p + 9, 2));
				if ((vt == 0x1F || vt == 0x08) && p + 17 <= b.Length)
				{
					int n = BitConverter.ToInt32(b.Slice(p + 13, 4));
					int bytes = vt == 0x1F ? n * 2 : n;
					if (bytes > 0 && p + 17 + bytes <= b.Length)
					{
						string s = Encoding.Unicode.GetString(b.Slice(p + 17, bytes)).TrimEnd('\0');
						if (pid == 5) aumid = s;
						else if (pid == 17) family = s;
					}
				}
				p += vsize;
			}
			o += ssize;
		}
	}

	private static string? Utf16Z(ReadOnlySpan<byte> b, int start, int end)
	{
		if (start < 0 || start >= end)
		{
			return null;
		}
		int i = start;
		while (i + 1 < end && (b[i] != 0 || b[i + 1] != 0))
		{
			i += 2;
		}
		return i > start ? Encoding.Unicode.GetString(b.Slice(start, i - start)) : null;
	}
}

// Change signal for the Taskband key: zero idle cost (one registered wait, no polling, no thread). Explorer's pin verb
// writes Favorites, FavoritesResolve and FavoritesChanges in a burst ~15 ms after it creates the .lnk, so the callback
// is debounced. The launcher only reads the key; TaskbarPinListMutex is never taken (it could block Explorer).
//
// When the key is deleted (a taskbar reset, or Explorer re-creating it), the open handle never sees the new key and
// re-arming fails (ERROR_KEY_DELETED): the key is then reopened by path, with backoff while it is missing, and the
// owner is told so it can catch up.
internal sealed class TaskbandChangeWatcher : IDisposable
{
	[DllImport("advapi32.dll")]
	private static extern int RegNotifyChangeKeyValue(SafeRegistryHandle hKey, bool bWatchSubtree, uint dwNotifyFilter, SafeWaitHandle hEvent, bool fAsynchronous);

	private const uint REG_NOTIFY_CHANGE_NAME = 0x1;

	private const uint REG_NOTIFY_CHANGE_LAST_SET = 0x4;

	// Win8+: the registration is not tied to the arming thread (thread-pool threads come and go; without this flag the
	// watch silently ends when that thread exits).
	private const uint REG_NOTIFY_THREAD_AGNOSTIC = 0x10000000;

	private readonly string _keyPath;

	private RegistryKey? _key;

	private readonly AutoResetEvent _signal = new AutoResetEvent(false);

	private readonly Timer _debounce;

	private readonly Action _changed;

	private readonly Action _recovered;

	private readonly int[] _recoveryDelaysMs;

	private readonly int _maxRecoveryAttempts;

	private readonly object _gate = new object();

	private RegisteredWaitHandle? _wait;

	private Timer? _reopen;

	private int _reopenAttempts;

	private bool _armed;

	private volatile bool _disposed;

	private TaskbandChangeWatcher(string keyPath, RegistryKey key, Action changed, Action recovered, int debounceMs, int[] recoveryDelaysMs, int maxRecoveryAttempts)
	{
		_keyPath = keyPath;
		_key = key;
		_changed = changed;
		_recovered = recovered;
		_recoveryDelaysMs = recoveryDelaysMs.Length > 0 ? recoveryDelaysMs : new[] { 1000 };
		_maxRecoveryAttempts = Math.Max(1, maxRecoveryAttempts);
		DebounceMs = debounceMs;
		_debounce = new Timer(_ =>
		{
			if (!_disposed)
			{
				_changed();
			}
		}, null, Timeout.Infinite, Timeout.Infinite);
	}

	public int DebounceMs { get; }

	// A registration is pending: changes are seen. False while the key is being reopened.
	public bool IsArmed
	{
		get
		{
			lock (_gate)
			{
				return _armed && !_disposed;
			}
		}
	}

	// Null when the key cannot be opened or the first registration fails (the caller logs and runs without live sync).
	public static TaskbandChangeWatcher? TryCreate(string keyPath, Action changed, Action recovered, int debounceMs, int[] recoveryDelaysMs, int maxRecoveryAttempts, out string? error)
	{
		error = null;
		RegistryKey? key = null;
		try
		{
			key = Registry.CurrentUser.OpenSubKey(keyPath, writable: false);
			if (key == null)
			{
				error = "key missing";
				return null;
			}
			TaskbandChangeWatcher w = new TaskbandChangeWatcher(keyPath, key, changed, recovered, debounceMs, recoveryDelaysMs, maxRecoveryAttempts);
			if (!w.Arm(out int rc))
			{
				error = "RegNotifyChangeKeyValue failed (" + rc + ")";
				w.Dispose();
				return null;
			}
			return w;
		}
		catch (Exception ex)
		{
			error = ex.Message;
			key?.Dispose();
			return null;
		}
	}

	private bool Arm(out int rc)
	{
		rc = 0;
		lock (_gate)
		{
			if (_disposed || _key == null)
			{
				_armed = false;
				return false;
			}
			try
			{
				rc = RegNotifyChangeKeyValue(_key.Handle, false, REG_NOTIFY_CHANGE_LAST_SET | REG_NOTIFY_CHANGE_NAME | REG_NOTIFY_THREAD_AGNOSTIC, _signal.SafeWaitHandle, true);
				if (rc != 0)
				{
					_armed = false;
					return false;
				}
				_wait?.Unregister(null);
				_wait = ThreadPool.RegisterWaitForSingleObject(_signal, OnSignal, null, Timeout.Infinite, executeOnlyOnce: true);
				_armed = true;
				return true;
			}
			catch (ObjectDisposedException)
			{
				_armed = false;
				return false;
			}
		}
	}

	private void OnSignal(object? state, bool timedOut)
	{
		// Re-arm first so a write during the debounce window is not lost.
		if (!Arm(out int rc) && !_disposed)
		{
			Lost(rc);
		}
		try
		{
			if (!_disposed)
			{
				_debounce.Change(DebounceMs, Timeout.Infinite);
			}
		}
		catch (ObjectDisposedException)
		{
		}
	}

	private void Lost(int rc)
	{
		lock (_gate)
		{
			if (_disposed)
			{
				return;
			}
			_armed = false;
			try { _key?.Dispose(); } catch { }
			_key = null;
			_reopenAttempts = 0;
			_reopen ??= new Timer(_ => Reopen(), null, Timeout.Infinite, Timeout.Infinite);
			_reopen.Change(_recoveryDelaysMs[0], Timeout.Infinite);
		}
		Logger.Log($"Pin sync: native taskbar watch lost (error {rc}); reopening the key");
	}

	private void Reopen()
	{
		bool recovered = false, gaveUp = false;
		lock (_gate)
		{
			if (_disposed || _armed)
			{
				return;
			}
			RegistryKey? key = null;
			try
			{
				key = Registry.CurrentUser.OpenSubKey(_keyPath, writable: false);
			}
			catch
			{
			}
			if (key != null)
			{
				_key = key;
				if (Arm(out _))
				{
					recovered = true;
				}
				else
				{
					try { key.Dispose(); } catch { }
					_key = null;
				}
			}
			if (!recovered)
			{
				_reopenAttempts++;
				if (_reopenAttempts >= _maxRecoveryAttempts)
				{
					gaveUp = true;
				}
				else
				{
					_reopen?.Change(_recoveryDelaysMs[Math.Min(_reopenAttempts, _recoveryDelaysMs.Length - 1)], Timeout.Infinite);
				}
			}
		}
		if (recovered)
		{
			Logger.Log("Pin sync: native taskbar watch recovered");
			try
			{
				_recovered();
			}
			catch
			{
			}
		}
		else if (gaveUp)
		{
			Logger.Log("Pin sync: native taskbar watch could not be restored; taskbar changes are picked up at the next start");
		}
	}

	public void Dispose()
	{
		lock (_gate)
		{
			if (_disposed)
			{
				return;
			}
			_disposed = true;
			_armed = false;
			try { _wait?.Unregister(null); } catch { }
			try { _debounce.Dispose(); } catch { }
			try { _reopen?.Dispose(); } catch { }
			try { _key?.Dispose(); } catch { }   // closing the key completes the pending notification
			try { _signal.Dispose(); } catch { }
		}
	}
}
