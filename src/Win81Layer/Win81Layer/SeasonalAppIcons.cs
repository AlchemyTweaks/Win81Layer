// One app identity as a surface knows it. Every field may be null.
internal readonly record struct SeasonalIdentity(string? ExePath, string? Args, string? Aumid, string? DisplayName, string? ProcessName);

// Seasonal app icons. While Halloween or Christmas is on (and the "Seasonal app icons" setting is on), an app that has a
// picture in <launcher folder>\seasonal\<season>-icons shows that picture on every surface the launcher draws instead of
// its own icon. Everything happens at render time: no shortcut, registry value, icon cache or other process is touched,
// so the only state is the season and the setting, and Normal brings the real icons back exactly.
//
// Files: <name>.png is the master, <name>-<n>.png (n = 8..1024) a pre-sized frame. The key is the name in lower case
// with only a-z and 0-9 kept. An optional aliases.txt maps more names to a key ("discord = discordptb, discordcanary").
// A surface asks for a size in physical pixels and gets the exact frame when there is one, otherwise a frame at least
// twice as large (or the master) scaled down with an area filter, so small sizes stay sharp.
//
// Idle cost: no timers, watchers or threads. The folder is read when the season or the setting changes (Reconcile),
// when PC Settings opens the Launcher page, or lazily on first use. When no season is on, every lookup returns null
// after two field reads.
internal static class SeasonalAppIcons
{
	// Raised on the UI thread after the state changed and the Start screen and taskbars were refreshed.
	internal static event Action? Changed;

	private const long MaxFileBytes = 8L * 1024 * 1024;

	private const int MaxPixels = 2048;

	private const int MaxFrameCache = 256;

	private const int MaxMemo = 4096;

	private static readonly object Gate = new object();

	private static readonly object LogGate = new object();

	private static readonly HashSet<string> Logged = new HashSet<string>(StringComparer.Ordinal);

	private static readonly Regex SizedName = new Regex("^(?<name>.+)-(?<n>[0-9]{1,4})$", RegexOptions.CultureInvariant);

	private static readonly Regex ProcessStart = new Regex("--processStart(?:AndWait)?\\s+\"?([^\"\\s]+\\.exe)\"?", RegexOptions.IgnoreCase | RegexOptions.CultureInvariant);

	// The shell itself: File Explorer windows and items never take a seasonal icon, whatever else they carry.
	private static readonly HashSet<string> ShellExes = new HashSet<string>(StringComparer.OrdinalIgnoreCase)
	{
		"explorer.exe"
	};

	// Executables that host many apps (with TaskbarWindow.SharedHostExes, for example ApplicationFrameHost for Store
	// apps). They say nothing about which app it is, so they are left out and the window's AUMID decides.
	private static readonly HashSet<string> HostExes = new HashSet<string>(StringComparer.OrdinalIgnoreCase)
	{
		"wwahost.exe", "msedgewebview2.exe"
	};

	// AUMID segments that say nothing about which app it is.
	private static readonly HashSet<string> StopTokens = new HashSet<string>(StringComparer.Ordinal)
	{
		"com", "org", "net", "io", "co", "app", "apps", "application", "id", "exe", "desktop", "electron", "squirrel",
		"microsoft", "windows", "google", "mozilla", "userdata", "autogenerated", "default", "main", "client", "launcher",
		"beta", "x64", "x86"
	};

	private static readonly HashSet<string> StopAppIds = new HashSet<string>(StringComparer.Ordinal)
	{
		"app", "application", "main", "default"
	};

	private static volatile State? _state;

	// The answer while a settings change waits for its Reconcile (see Current).
	private static volatile State? _provisional;

	private static int _version;

	private static int _healPending;

	// Set when a provisional state that shows icons answered a lookup, so its Reconcile refreshes the surfaces even
	// when the settings went back to the applied state in the meantime.
	private static int _provisionalShown;

	private static int _selfHealPosts;

	private static int _ioCount;

	// QA: when set, log lines are also collected here.
	internal static List<string>? QaLog { get; set; }

	// QA (read-only diagnostics only): the folder that holds <season>-icons instead of the launcher folder.
	internal static string? DiagnosticsRoot { get; set; }

	internal static int Version => Volatile.Read(ref _version);

	// Number of file-system touches (folder listings, header reads, decodes, shortcut reads). QA only.
	internal static int IoCount => Volatile.Read(ref _ioCount);

	internal static int SelfHealPosts => Volatile.Read(ref _selfHealPosts);

	internal static bool IsActive => Current().Active;

	// "" when no seasonal icons are shown.
	internal static string ActiveSeason
	{
		get
		{
			State s = Current();
			return s.Active ? s.Season : "";
		}
	}

	internal static string RootDir => (SettingsStore.ReadOnlyDiagnostics && !string.IsNullOrEmpty(DiagnosticsRoot))
		? DiagnosticsRoot!
		: Path.Combine(AppContext.BaseDirectory, "seasonal");

	internal static string FolderFor(string season)
	{
		return Path.Combine(RootDir, SeasonalTheme.NormalizeId(season) + "-icons");
	}

	// ===================================================================== state

	private readonly record struct FrameFile(int Px, string Path, bool Sized);

	private sealed class State
	{
		public static readonly Dictionary<string, FrameFile[]> NoKeys = new Dictionary<string, FrameFile[]>(StringComparer.Ordinal);

		public static readonly Dictionary<string, string> NoAliases = new Dictionary<string, string>(StringComparer.Ordinal);

		// The raw settings this state answers for. Raw is updated in place when only its spelling changes.
		public volatile string Raw;

		public readonly bool Enabled;

		public readonly string Season;

		public readonly string Stamp;

		public readonly Dictionary<string, FrameFile[]> Keys;

		public readonly Dictionary<string, string> Aliases;

		public readonly bool Active;

		public readonly ConcurrentDictionary<string, string?> Memo = new ConcurrentDictionary<string, string?>(StringComparer.Ordinal);

		public readonly ConcurrentDictionary<string, Brush> Brushes = new ConcurrentDictionary<string, Brush>(StringComparer.Ordinal);

		public readonly object FrameGate = new object();

		public readonly Dictionary<(string Key, int Px), BitmapSource?> Frames = new Dictionary<(string, int), BitmapSource?>();

		public State(string raw, bool enabled, string season, string stamp, Dictionary<string, FrameFile[]> keys, Dictionary<string, string> aliases)
		{
			Raw = raw;
			Enabled = enabled;
			Season = season;
			Stamp = stamp;
			Keys = keys;
			Aliases = aliases;
			Active = season.Length > 0 && enabled && keys.Count > 0;
		}

		public bool Matches(string raw, bool enabled)
		{
			return enabled == Enabled && string.Equals(raw, Raw, StringComparison.Ordinal);
		}
	}

	// The state for the current settings. The applied state normally matches them; after a change that has not been
	// reconciled yet (for example the settings were written by another path), the answer comes from a provisional
	// state for the new values and one Reconcile is posted to the UI thread to refresh the surfaces.
	private static State Current()
	{
		State? s = _state ?? Init();
		(string raw, bool enabled) = SettingsStore.PeekSeasonalAppIcons();
		if (s.Matches(raw, enabled))
		{
			return s;
		}
		State? p = _provisional;
		if (p == null || !p.Matches(raw, enabled))
		{
			lock (Gate)
			{
				p = _provisional;
				if (p == null || !p.Matches(raw, enabled))
				{
					p = Build(raw, enabled, null);
					_provisional = p;
				}
			}
		}
		if (p.Active)
		{
			Volatile.Write(ref _provisionalShown, 1);
		}
		PostSelfHeal();
		return p;
	}

	private static State Init()
	{
		lock (Gate)
		{
			State? s = _state;
			if (s != null)
			{
				return s;
			}
			(string raw, bool enabled) = SettingsStore.PeekSeasonalAppIcons();
			s = Build(raw, enabled, null);
			_state = s;
			LogState(s, "start");
			return s;
		}
	}

	private static void PostSelfHeal()
	{
		Dispatcher? ui = Application.Current?.Dispatcher;
		if (ui == null || ui.HasShutdownStarted || Interlocked.CompareExchange(ref _healPending, 1, 0) != 0)
		{
			return;
		}
		Interlocked.Increment(ref _selfHealPosts);
		try
		{
			ui.BeginInvoke((Action)delegate
			{
				Reconcile("self-heal");
			});
		}
		catch
		{
			Interlocked.Exchange(ref _healPending, 0);
		}
	}

	// Brings the state in line with the settings and the folder, and refreshes every surface when anything changed.
	// UI thread (other threads are marshalled).
	internal static void Reconcile(string reason)
	{
		Dispatcher? ui = Application.Current?.Dispatcher;
		if (ui != null && !ui.CheckAccess())
		{
			ui.BeginInvoke((Action)delegate
			{
				Reconcile(reason);
			});
			return;
		}
		Interlocked.Exchange(ref _healPending, 0);
		State next;
		State? cur;
		bool shown;
		lock (Gate)
		{
			(string raw, bool enabled) = SettingsStore.PeekSeasonalAppIcons();
			cur = _state;
			State? provisional = _provisional;
			// The folder listing alone decides whether anything changed; PNG headers are read only when it did.
			next = Build(raw, enabled, cur, provisional);
			_provisional = null;
			shown = Interlocked.Exchange(ref _provisionalShown, 0) == 1;
			if (cur != null && cur.Stamp == next.Stamp)
			{
				cur.Raw = raw;
				if (!shown)
				{
					return;
				}
				// A provisional state showed icons that the applied one does not: bring the surfaces back to it.
				next = cur;
			}
			else
			{
				_state = next;
			}
			Interlocked.Increment(ref _version);
		}
		if (!ReferenceEquals(next, cur))
		{
			LogState(next, reason);
		}
		// Between two states that show nothing (Normal with the setting flipped, or a season without icons) every
		// surface already shows its own icon, so there is nothing to refresh.
		if (shown || (cur?.Active ?? false) || next.Active)
		{
			RefreshSurfaces();
		}
	}

	private static void RefreshSurfaces()
	{
		try
		{
			StartScreen.RefreshSeasonalIcons();
		}
		catch (Exception ex)
		{
			Logger.Log("Seasonal icons: Start refresh failed: " + ex.Message);
		}
		try
		{
			// Seasonal frames never enter the pin icon cache, so the other pins keep their cached icons.
			TaskbarWindow.RebuildPinsForSeasonal();
		}
		catch (Exception ex)
		{
			Logger.Log("Seasonal icons: taskbar pins refresh failed: " + ex.Message);
		}
		try
		{
			TaskbarWindow.RaiseSeasonalIconsChanged();
		}
		catch (Exception ex)
		{
			Logger.Log("Seasonal icons: taskbar refresh failed: " + ex.Message);
		}
		Action? handlers = Changed;
		if (handlers == null)
		{
			return;
		}
		foreach (Delegate d in handlers.GetInvocationList())
		{
			try
			{
				((Action)d)();
			}
			catch (Exception ex)
			{
				Logger.Log("Seasonal icons: a Changed handler failed: " + ex.Message);
			}
		}
	}

	private static void LogState(State s, string reason)
	{
		string line = s.Active
			? $"Seasonal icons: {s.Season} ({reason}): {s.Keys.Count} app{(s.Keys.Count == 1 ? "" : "s")} [{string.Join(", ", s.Keys.Keys.OrderBy(k => k, StringComparer.Ordinal))}]"
			: $"Seasonal icons: off ({reason}){(s.Season.Length > 0 && s.Enabled ? ": no icons for " + s.Season : "")}";
		Write(line);
	}

	// ===================================================================== folder scan

	// The state for these settings. When the folder listing (names, sizes, times) gives the stamp of one of the reuse
	// states, that state is returned as it is and no file is opened.
	private static State Build(string raw, bool enabled, State? reuse, State? reuse2 = null)
	{
		raw ??= "";
		string season = SeasonalTheme.NormalizeId(raw);
		if (!SeasonalTheme.IsSeason(season))
		{
			// Dark rest has no icon set: the apps keep their own icons.
			season = "";
		}
		string head = season + "|" + (enabled ? "1" : "0");
		if (season.Length == 0 || !enabled)
		{
			return Reuse(head, raw, reuse, reuse2) ?? new State(raw, enabled, season, head, State.NoKeys, State.NoAliases);
		}
		string dir = FolderFor(season);
		StringBuilder stamp = new StringBuilder(head).Append('|').Append(dir).Append('|');
		FileInfo[] files = Array.Empty<FileInfo>();
		try
		{
			CountIo();
			DirectoryInfo di = new DirectoryInfo(dir);
			if (!di.Exists)
			{
				stamp.Append("(none)");
			}
			else
			{
				files = di.GetFiles();
				Array.Sort(files, (FileInfo a, FileInfo b) => StringComparer.OrdinalIgnoreCase.Compare(a.Name, b.Name));
				foreach (FileInfo f in files)
				{
					stamp.Append(f.Name).Append(':').Append(f.Length).Append(':').Append(f.LastWriteTimeUtc.Ticks).Append(';');
				}
			}
		}
		catch (Exception ex)
		{
			files = Array.Empty<FileInfo>();
			stamp.Append("(error)");
			LogOnce("scan|" + dir, "Seasonal icons: could not read " + dir + ": " + ex.Message);
		}
		string stampText = stamp.ToString();
		if (Reuse(stampText, raw, reuse, reuse2) is State same)
		{
			return same;
		}
		Dictionary<string, List<FrameFile>> found = new Dictionary<string, List<FrameFile>>(StringComparer.Ordinal);
		string? aliasFile = null;
		foreach (FileInfo f in files)
		{
			if (f.Name.Equals("aliases.txt", StringComparison.OrdinalIgnoreCase))
			{
				aliasFile = f.FullName;
			}
			else if (f.Extension.Equals(".png", StringComparison.OrdinalIgnoreCase))
			{
				AddFrame(found, f);
			}
		}
		Dictionary<string, FrameFile[]> keys = new Dictionary<string, FrameFile[]>(StringComparer.Ordinal);
		foreach (KeyValuePair<string, List<FrameFile>> kv in found)
		{
			// One file per size; a pre-sized file wins over a master of the same size.
			FrameFile[] frames = kv.Value
				.OrderBy(f => f.Px)
				.ThenBy(f => f.Sized ? 0 : 1)
				.GroupBy(f => f.Px)
				.Select(g => g.First())
				.ToArray();
			keys[kv.Key] = frames;
		}
		Dictionary<string, string> aliases = aliasFile != null && keys.Count > 0 ? ReadAliases(aliasFile, keys) : State.NoAliases;
		return new State(raw, enabled, season, stampText, keys, aliases);
	}

	private static State? Reuse(string stamp, string raw, State? a, State? b)
	{
		State? hit = (a != null && a.Stamp == stamp) ? a : (b != null && b.Stamp == stamp) ? b : null;
		if (hit != null)
		{
			hit.Raw = raw;
		}
		return hit;
	}

	private static void AddFrame(Dictionary<string, List<FrameFile>> found, FileInfo f)
	{
		string stem = Path.GetFileNameWithoutExtension(f.Name);
		string name = stem;
		int suffix = 0;
		Match m = SizedName.Match(stem);
		if (m.Success && int.TryParse(m.Groups["n"].Value, NumberStyles.None, CultureInfo.InvariantCulture, out int n) && n >= 8 && n <= 1024)
		{
			name = m.Groups["name"].Value;
			suffix = n;
		}
		string key = Normalize(name);
		if (key.Length == 0)
		{
			return;
		}
		if (f.Length > MaxFileBytes)
		{
			LogOnce("big|" + f.FullName, $"Seasonal icons: skipped {f.Name}: larger than 8 MB.");
			return;
		}
		(int w, int h) = PngSize(f.FullName);
		if (w <= 0 || h <= 0)
		{
			LogOnce("png|" + f.FullName, $"Seasonal icons: skipped {f.Name}: not a readable PNG.");
			return;
		}
		if (w > MaxPixels || h > MaxPixels)
		{
			LogOnce("px|" + f.FullName, $"Seasonal icons: skipped {f.Name}: {w}x{h} is larger than {MaxPixels} px.");
			return;
		}
		int px = Math.Max(w, h);
		if (suffix > 0 && suffix != px)
		{
			LogOnce("size|" + f.FullName, $"Seasonal icons: {f.Name} is {w}x{h}; using its real size {px} px.");
		}
		if (!found.TryGetValue(key, out List<FrameFile>? list))
		{
			list = new List<FrameFile>();
			found[key] = list;
		}
		list.Add(new FrameFile(px, f.FullName, suffix > 0));
	}

	// Width and height from the PNG IHDR header, (0, 0) when the file is not a PNG.
	private static (int W, int H) PngSize(string path)
	{
		try
		{
			CountIo();
			byte[] h = new byte[24];
			using (FileStream fs = new FileStream(path, FileMode.Open, FileAccess.Read, FileShare.ReadWrite | FileShare.Delete))
			{
				if (fs.ReadAtLeast(h, h.Length, throwOnEndOfStream: false) < h.Length)
				{
					return (0, 0);
				}
			}
			bool png = h[0] == 0x89 && h[1] == (byte)'P' && h[2] == (byte)'N' && h[3] == (byte)'G'
				&& h[12] == (byte)'I' && h[13] == (byte)'H' && h[14] == (byte)'D' && h[15] == (byte)'R';
			if (!png)
			{
				return (0, 0);
			}
			int w = System.Buffers.Binary.BinaryPrimitives.ReadInt32BigEndian(h.AsSpan(16, 4));
			int ht = System.Buffers.Binary.BinaryPrimitives.ReadInt32BigEndian(h.AsSpan(20, 4));
			return (w, ht);
		}
		catch
		{
			return (0, 0);
		}
	}

	// "key = alias1, alias2" per line (':' works too); '#' starts a comment.
	private static Dictionary<string, string> ReadAliases(string path, Dictionary<string, FrameFile[]> keys)
	{
		Dictionary<string, string> map = new Dictionary<string, string>(StringComparer.Ordinal);
		try
		{
			CountIo();
			string text;
			using (FileStream fs = new FileStream(path, FileMode.Open, FileAccess.Read, FileShare.ReadWrite | FileShare.Delete))
			{
				if (fs.Length > 64 * 1024)
				{
					LogOnce("aliasbig|" + path, "Seasonal icons: aliases.txt is larger than 64 KB and was ignored.");
					return map;
				}
				using StreamReader reader = new StreamReader(fs, Encoding.UTF8, detectEncodingFromByteOrderMarks: true);
				text = reader.ReadToEnd();
			}
			foreach (string rawLine in text.Split('\n'))
			{
				string line = rawLine;
				int hash = line.IndexOf('#');
				if (hash >= 0)
				{
					line = line.Substring(0, hash);
				}
				int sep = line.IndexOfAny(new char[2] { '=', ':' });
				if (sep <= 0)
				{
					continue;
				}
				string key = Normalize(line.Substring(0, sep));
				if (!keys.ContainsKey(key))
				{
					continue;
				}
				foreach (string part in line.Substring(sep + 1).Split(','))
				{
					string alias = Normalize(part);
					if (alias.Length > 0 && !keys.ContainsKey(alias))
					{
						map.TryAdd(alias, key);
					}
				}
			}
		}
		catch (Exception ex)
		{
			LogOnce("alias|" + path, "Seasonal icons: could not read aliases.txt: " + ex.Message);
		}
		return map;
	}

	// The keys that have a picture for a season, sorted (for PC Settings and QA). The active season answers from the
	// state its last Reconcile built; another season reads its folder.
	internal static IReadOnlyList<string> KeysFor(string season)
	{
		string id = SeasonalTheme.NormalizeId(season);
		State? applied = _state;
		State s;
		if (applied != null && applied.Enabled && id.Length > 0 && applied.Season == id)
		{
			s = applied;
		}
		else
		{
			lock (Gate)
			{
				SideStates.TryGetValue(id, out State? side);
				s = Build(id, true, side);
				SideStates[id] = s;
			}
		}
		return s.Keys.Keys.OrderBy(k => k, StringComparer.Ordinal).ToList();
	}

	// The last listing of each season that is not the applied one, so PC Settings reads only headers that changed.
	private static readonly Dictionary<string, State> SideStates = new Dictionary<string, State>(StringComparer.Ordinal);

	// ===================================================================== matching

	internal static string Normalize(string? name)
	{
		if (string.IsNullOrEmpty(name))
		{
			return "";
		}
		StringBuilder sb = new StringBuilder(name.Length);
		foreach (char c in name.ToLowerInvariant())
		{
			if ((c >= 'a' && c <= 'z') || (c >= '0' && c <= '9'))
			{
				sb.Append(c);
			}
		}
		return sb.ToString();
	}

	// The seasonal key for an identity, or null. Pure apart from the season's key set; results are memoised per state.
	internal static string? KeyForIdentity(in SeasonalIdentity id)
	{
		State s = Current();
		if (!s.Active)
		{
			return null;
		}
		string sig = string.Join("\u0001", id.ExePath, id.Args, id.Aumid, id.DisplayName, id.ProcessName);
		if (s.Memo.TryGetValue(sig, out string? cached))
		{
			return cached;
		}
		string? key = Match(s, id);
		if (s.Memo.Count >= MaxMemo)
		{
			s.Memo.Clear();
		}
		s.Memo[sig] = key;
		return key;
	}

	private static string? Match(State s, in SeasonalIdentity id)
	{
		string? exe = StripAppsFolder(Clean(id.ExePath));
		string? aumid = StripAppsFolder(Clean(id.Aumid));
		string? args = id.Args;
		string? proc = Clean(id.ProcessName);
		if (proc != null && proc.EndsWith(".exe", StringComparison.OrdinalIgnoreCase))
		{
			proc = proc.Substring(0, proc.Length - 4);
		}
		// Identities that never take a seasonal icon: Chromium web apps, shared hosts and launcher entries.
		if (aumid != null && aumid.IndexOf("_crx_", StringComparison.OrdinalIgnoreCase) >= 0)
		{
			return null;
		}
		if (args != null && (args.IndexOf("--app-id=", StringComparison.OrdinalIgnoreCase) >= 0 || args.IndexOf("--app=", StringComparison.OrdinalIgnoreCase) >= 0))
		{
			return null;
		}
		if (IsLauncherPath(exe) || IsLauncherPath(aumid))
		{
			return null;
		}
		string? exeName = exe != null ? FileName(exe) : null;
		if (IsShellExe(exeName) || (proc != null && IsShellExe(proc + ".exe")))
		{
			return null;
		}
		// A shared host (ApplicationFrameHost for a Store app's window, rundll32, ...) is not the app: drop it and go on
		// with the AUMID. A host with nothing else to go on still matches nothing.
		if (IsHostExe(exeName))
		{
			exeName = null;
		}
		if (proc != null && IsHostExe(proc + ".exe"))
		{
			proc = null;
		}
		// An AUMID that is really a path (a classic app's AppsFolder id) is an executable, not dotted segments.
		string? aumidExe = null;
		if (aumid != null && (aumid.IndexOf('\\') >= 0 || aumid.IndexOf(':') >= 0))
		{
			aumidExe = FileName(aumid);
			if (IsShellExe(aumidExe))
			{
				return null;
			}
			if (IsHostExe(aumidExe))
			{
				aumidExe = null;
			}
			aumid = null;
		}

		// 1. executable stem (Squirrel's Update.exe --processStart X.exe means X)
		string? key = TryExe(s, exeName, args);
		if (key != null)
		{
			return key;
		}
		key = TryExe(s, aumidExe, args);
		if (key != null)
		{
			return key;
		}
		if (proc != null && (key = Lookup(s, Normalize(proc))) != null)
		{
			return key;
		}
		// 2. AUMID tokens
		if (aumid != null)
		{
			foreach (string token in AumidTokens(aumid))
			{
				if ((key = Lookup(s, token)) != null)
				{
					return key;
				}
			}
		}
		// 3. the whole display name (never single words, so "Notion Calendar" is not Notion)
		if (!string.IsNullOrWhiteSpace(id.DisplayName))
		{
			return Lookup(s, Normalize(id.DisplayName));
		}
		return null;
	}

	private static string? TryExe(State s, string? exeName, string? args)
	{
		if (string.IsNullOrEmpty(exeName) || !exeName.EndsWith(".exe", StringComparison.OrdinalIgnoreCase))
		{
			return null;
		}
		string stem = exeName.Substring(0, exeName.Length - 4);
		if (stem.Equals("update", StringComparison.OrdinalIgnoreCase) && !string.IsNullOrEmpty(args))
		{
			Match m = ProcessStart.Match(args);
			if (m.Success)
			{
				string target = FileName(m.Groups[1].Value);
				if (IsShellExe(target) || IsHostExe(target))
				{
					return null;
				}
				stem = target.Substring(0, target.Length - 4);
			}
		}
		return Lookup(s, Normalize(stem));
	}

	private static string? Lookup(State s, string token)
	{
		if (token.Length == 0)
		{
			return null;
		}
		if (s.Keys.ContainsKey(token))
		{
			return token;
		}
		return s.Aliases.TryGetValue(token, out string? key) ? key : null;
	}

	// Packaged "Family_hash!AppId": the AppId first, then the family's dotted segments from right to left. Unpackaged:
	// the dotted segments from left to right. Generic, numeric and hash-like segments are skipped.
	private static IEnumerable<string> AumidTokens(string aumid)
	{
		int bang = aumid.IndexOf('!');
		if (bang > 0)
		{
			string appId = Normalize(aumid.Substring(bang + 1));
			if (!StopAppIds.Contains(appId) && UsefulToken(appId))
			{
				yield return appId;
			}
			string family = aumid.Substring(0, bang);
			int us = family.LastIndexOf('_');
			if (us > 0)
			{
				family = family.Substring(0, us);
			}
			string[] parts = family.Split('.');
			for (int i = parts.Length - 1; i >= 0; i--)
			{
				string t = Normalize(parts[i]);
				if (UsefulToken(t))
				{
					yield return t;
				}
			}
			yield break;
		}
		foreach (string part in aumid.Split('.'))
		{
			string t = Normalize(part);
			if (UsefulToken(t))
			{
				yield return t;
			}
		}
	}

	private static bool UsefulToken(string t)
	{
		if (t.Length < 3 || StopTokens.Contains(t))
		{
			return false;
		}
		bool digits = true;
		bool hex = true;
		foreach (char c in t)
		{
			digits &= c >= '0' && c <= '9';
			hex &= (c >= '0' && c <= '9') || (c >= 'a' && c <= 'f');
		}
		return !digits && !(hex && t.Length >= 8);
	}

	private static bool IsShellExe(string? exeName)
	{
		return !string.IsNullOrEmpty(exeName) && ShellExes.Contains(exeName);
	}

	private static bool IsHostExe(string? exeName)
	{
		if (string.IsNullOrEmpty(exeName))
		{
			return false;
		}
		if (HostExes.Contains(exeName))
		{
			return true;
		}
		foreach (string host in TaskbarWindow.SharedHostExes)
		{
			if (exeName.Equals(host, StringComparison.OrdinalIgnoreCase))
			{
				return true;
			}
		}
		return false;
	}

	// win81:, launcher://, qa: and every other scheme except shell: (web links, ms-settings:, folder tiles).
	private static bool IsLauncherPath(string? path)
	{
		if (string.IsNullOrEmpty(path))
		{
			return false;
		}
		if (path.StartsWith("win81:", StringComparison.OrdinalIgnoreCase)
			|| path.StartsWith(ActionRouter.Scheme, StringComparison.OrdinalIgnoreCase)
			|| path.StartsWith("qa:", StringComparison.OrdinalIgnoreCase))
		{
			return true;
		}
		int colon = path.IndexOf(':');
		if (colon <= 1 || path.StartsWith("shell:", StringComparison.OrdinalIgnoreCase))
		{
			return false;
		}
		for (int i = 0; i < colon; i++)
		{
			char c = path[i];
			if (!char.IsAsciiLetterOrDigit(c) && c != '+' && c != '.' && c != '-')
			{
				return false;
			}
		}
		return true;
	}

	private static string? Clean(string? s)
	{
		if (string.IsNullOrWhiteSpace(s))
		{
			return null;
		}
		return s.Trim().Trim('"');
	}

	private static string? StripAppsFolder(string? s)
	{
		const string prefix = "shell:AppsFolder\\";
		if (s != null && s.StartsWith(prefix, StringComparison.OrdinalIgnoreCase))
		{
			s = s.Substring(prefix.Length);
			return s.Length == 0 ? null : s;
		}
		return s;
	}

	private static string FileName(string path)
	{
		int cut = path.LastIndexOfAny(new char[2] { '\\', '/' });
		return cut >= 0 ? path.Substring(cut + 1) : path;
	}

	// ===================================================================== surface identities

	// A Start / all-apps / Windows 7 menu entry. Live tiles and the launcher's own entries never match.
	internal static string? KeyForEntry(AppEntry? e)
	{
		State s = Current();
		if (!s.Active || e == null)
		{
			return null;
		}
		string lp = e.LaunchPath ?? "";
		if (IsLauncherPath(lp))
		{
			return null;
		}
		string sig = "entry\u0001" + lp + "\u0001" + e.AppId + "\u0001" + e.Name;
		if (s.Memo.TryGetValue(sig, out string? cached))
		{
			return cached;
		}
		string? exe = null;
		string? aumid = string.IsNullOrWhiteSpace(e.AppId) ? null : e.AppId;
		string? parsing = StripAppsFolder(lp);
		if (!ReferenceEquals(parsing, lp) && parsing != null)
		{
			aumid ??= parsing;
			if (parsing.IndexOf('\\') >= 0 || parsing.IndexOf(':') >= 0)
			{
				exe = parsing;
			}
		}
		else if (lp.EndsWith(".exe", StringComparison.OrdinalIgnoreCase))
		{
			exe = lp;
		}
		else if (lp.EndsWith(".lnk", StringComparison.OrdinalIgnoreCase))
		{
			exe = LinkTarget(lp);
		}
		string? key = KeyForIdentity(new SeasonalIdentity(exe, null, aumid, e.Name, null));
		s.Memo[sig] = key;
		return key;
	}

	internal static string? KeyForPin(PinnedApp? p)
	{
		State s = Current();
		if (!s.Active || p == null)
		{
			return null;
		}
		string lp = p.LaunchPath ?? "";
		if (IsLauncherPath(lp))
		{
			return null;
		}
		string? exe = string.IsNullOrWhiteSpace(p.ExePath) ? null : p.ExePath;
		string? aumid = string.IsNullOrWhiteSpace(p.Aumid) ? null : p.Aumid;
		string? parsing = StripAppsFolder(lp);
		if (!ReferenceEquals(parsing, lp) && parsing != null)
		{
			aumid ??= parsing;
		}
		else if (lp.EndsWith(".exe", StringComparison.OrdinalIgnoreCase))
		{
			string? viaLaunch = KeyForIdentity(new SeasonalIdentity(lp, p.Args, null, null, null));
			if (viaLaunch != null)
			{
				return viaLaunch;
			}
			exe ??= lp;
		}
		else if (exe == null && lp.EndsWith(".lnk", StringComparison.OrdinalIgnoreCase))
		{
			exe = LinkTarget(lp);
		}
		return KeyForIdentity(new SeasonalIdentity(exe, p.Args, aumid, p.Name, null));
	}

	// A top-level window. Null arguments are queried from the window. Titles are never used.
	internal static string? KeyForWindow(nint hwnd, string? exePath, string? aumid)
	{
		if (!Current().Active)
		{
			return null;
		}
		if (exePath == null && hwnd != IntPtr.Zero)
		{
			exePath = WindowList.GetExePath(hwnd);
		}
		if (aumid == null && hwnd != IntPtr.Zero)
		{
			aumid = AppInventory.GetWindowAppId(hwnd);
		}
		if (string.IsNullOrEmpty(exePath) && string.IsNullOrEmpty(aumid))
		{
			return null;
		}
		return KeyForIdentity(new SeasonalIdentity(exePath, null, aumid, null, null));
	}

	// A process (notification-area icons, audio sessions): its name and, when known, its executable.
	internal static string? KeyForProcess(string? processName, string? exePath)
	{
		if (!Current().Active || (string.IsNullOrEmpty(processName) && string.IsNullOrEmpty(exePath)))
		{
			return null;
		}
		return KeyForIdentity(new SeasonalIdentity(exePath, null, null, null, processName));
	}

	private static string? LinkTarget(string lnkPath)
	{
		try
		{
			CountIo();
			FileInfo fi = new FileInfo(lnkPath);
			if (!fi.Exists || fi.Length > 1024 * 1024)
			{
				return null;
			}
			return ShellLink.GetTargetPath(File.ReadAllBytes(lnkPath));
		}
		catch
		{
			return null;
		}
	}

	// ===================================================================== frames

	// Physical pixels for a size in DIP on the sharpest monitor.
	internal static int Px(double dip)
	{
		double scale = 1.0;
		try
		{
			scale = AppIconOverrides.MaxMonitorScale();
		}
		catch
		{
		}
		return Math.Max(1, (int)Math.Ceiling(dip * scale - 0.0001));
	}

	// The key's picture at exactly px x px physical pixels (frozen, Pbgra32, 96 dpi), or null when none is shown.
	internal static ImageSource? Frame(string? key, int px)
	{
		if (key == null)
		{
			return null;
		}
		State s = Current();
		if (!s.Active || !s.Keys.TryGetValue(key, out FrameFile[]? frames))
		{
			return null;
		}
		px = Math.Clamp(px, 8, 1024);
		lock (s.FrameGate)
		{
			if (s.Frames.TryGetValue((key, px), out BitmapSource? hit))
			{
				return hit;
			}
		}
		BitmapSource? made = MakeFrame(key, frames, px);
		lock (s.FrameGate)
		{
			if (s.Frames.TryGetValue((key, px), out BitmapSource? raced))
			{
				return raced;
			}
			if (s.Frames.Count >= MaxFrameCache)
			{
				s.Frames.Clear();
			}
			s.Frames[(key, px)] = made;
		}
		return made;
	}

	private static BitmapSource? MakeFrame(string key, FrameFile[] frames, int px)
	{
		// Exactly this size: the file as supplied.
		foreach (FrameFile f in frames)
		{
			if (f.Px == px && Decode(f.Path) is BitmapSource exact)
			{
				return exact.PixelWidth == px && exact.PixelHeight == px ? exact : Fit(exact, px);
			}
		}
		// Otherwise an area downscale from the smallest frame at least twice as large, or else the largest larger frame
		// (usually the master). Scaling a frame only a little larger (20 to 18) would blend nearly every pixel with its
		// neighbour and look soft; from twice the size or more each output pixel is a clean average of its own area.
		IEnumerable<FrameFile> larger = frames.Where(f => f.Px >= 2 * px)
			.Concat(frames.Where(f => f.Px > px && f.Px < 2 * px).Reverse());
		foreach (FrameFile f in larger)
		{
			if (Decode(f.Path) is BitmapSource big)
			{
				return Fit(big, px);
			}
		}
		// Only smaller frames: the largest one, scaled up smoothly.
		for (int i = frames.Length - 1; i >= 0; i--)
		{
			if (frames[i].Px < px && Decode(frames[i].Path) is BitmapSource smaller)
			{
				LogOnce("up|" + key + "|" + px, $"Seasonal icons: {key} has no frame of {px} px or larger; scaling {Path.GetFileName(frames[i].Path)} up.");
				return Upscale(smaller, px);
			}
		}
		return null;
	}

	private static BitmapSource Fit(BitmapSource src, int px)
	{
		ImageSource fit = TrayIconFit.Fit(src, px);
		return fit as BitmapSource ?? src;
	}

	private static BitmapSource? Upscale(BitmapSource src, int px)
	{
		try
		{
			double k = Math.Min((double)px / src.PixelWidth, (double)px / src.PixelHeight);
			double w = src.PixelWidth * k;
			double h = src.PixelHeight * k;
			DrawingVisual dv = new DrawingVisual();
			RenderOptions.SetBitmapScalingMode(dv, BitmapScalingMode.HighQuality);
			using (DrawingContext dc = dv.RenderOpen())
			{
				dc.DrawImage(src, new Rect((px - w) / 2.0, (px - h) / 2.0, w, h));
			}
			RenderTargetBitmap rtb = new RenderTargetBitmap(px, px, 96.0, 96.0, PixelFormats.Pbgra32);
			rtb.Render(dv);
			byte[] pixels = new byte[px * px * 4];
			rtb.CopyPixels(pixels, px * 4, 0);
			BitmapSource result = BitmapSource.Create(px, px, 96.0, 96.0, PixelFormats.Pbgra32, null, pixels, px * 4);
			result.Freeze();
			return result;
		}
		catch (Exception ex)
		{
			Logger.Log("Seasonal icons: upscale failed: " + ex.Message);
			return null;
		}
	}

	// The file read into memory (never locked), decoded and copied into a frozen 96 dpi Pbgra32 bitmap. Any thread.
	private static BitmapSource? Decode(string path)
	{
		try
		{
			CountIo();
			byte[] bytes;
			using (FileStream fs = new FileStream(path, FileMode.Open, FileAccess.Read, FileShare.ReadWrite | FileShare.Delete))
			{
				if (fs.Length > MaxFileBytes)
				{
					LogOnce("big|" + path, $"Seasonal icons: skipped {Path.GetFileName(path)}: larger than 8 MB.");
					return null;
				}
				bytes = new byte[fs.Length];
				fs.ReadExactly(bytes);
			}
			using MemoryStream ms = new MemoryStream(bytes, writable: false);
			BitmapDecoder decoder = BitmapDecoder.Create(ms, BitmapCreateOptions.PreservePixelFormat | BitmapCreateOptions.IgnoreColorProfile, BitmapCacheOption.OnLoad);
			BitmapSource frame = decoder.Frames[0];
			int w = frame.PixelWidth;
			int h = frame.PixelHeight;
			if (w <= 0 || h <= 0 || w > MaxPixels || h > MaxPixels)
			{
				LogOnce("px|" + path, $"Seasonal icons: skipped {Path.GetFileName(path)}: {w}x{h}.");
				return null;
			}
			BitmapSource pbgra = frame.Format == PixelFormats.Pbgra32 ? frame : new FormatConvertedBitmap(frame, PixelFormats.Pbgra32, null, 0.0);
			byte[] pixels = new byte[w * h * 4];
			pbgra.CopyPixels(pixels, w * 4, 0);
			BitmapSource result = BitmapSource.Create(w, h, 96.0, 96.0, PixelFormats.Pbgra32, null, pixels, w * 4);
			result.Freeze();
			return result;
		}
		catch (Exception ex)
		{
			LogOnce("decode|" + path, $"Seasonal icons: could not decode {Path.GetFileName(path)}: {ex.Message}");
			return null;
		}
	}

	// The Start tile (and all-apps plate) colour for a seasonal icon. Painted seasonal art often sits on a dark backdrop
	// that would win a plain colour vote and vanish into the dark seasonal Start background, so only clearly coloured
	// pixels vote, and the result is kept in a luminance band: at least 1.6:1 against the season's Start background and
	// at least 4.5:1 for the white tile label. The hue is kept. Ordinary icons keep AppInventory.DominantColor.
	internal static Brush TileBrushFor(string key)
	{
		State s = Current();
		return s.Brushes.GetOrAdd(key, delegate(string k)
		{
			Color c = IconResolver.AccentFor(k);
			try
			{
				c = TileColorFor(Frame(k, 64) as BitmapSource, s.Season, k);
			}
			catch
			{
			}
			SolidColorBrush b = new SolidColorBrush(c);
			b.Freeze();
			return b;
		});
	}

	// Highest relative luminance of a tile behind a white label (white on it is 1.05 / 0.23 = 4.57:1).
	internal const double TileLumMax = 0.18;

	// Lowest relative luminance of a tile, and the contrast it keeps against the season's Start background.
	internal const double TileLumMin = 0.05;

	internal const double TileBgContrast = 1.6;

	internal static Color TileColorFor(BitmapSource? art, string season, string key)
	{
		Color c = IconResolver.AccentFor(key);
		if (art != null)
		{
			Color? found = VividColor(art) ?? AppInventory.DominantColor(art);
			if (found.HasValue)
			{
				c = found.Value;
			}
		}
		return FitTileLuminance(c, SeasonBackground(season));
	}

	// The Start background colour of a season preset, or null.
	internal static Color? SeasonBackground(string season)
	{
		SeasonPreset? p = SeasonalTheme.Find(season);
		return p != null ? StartBackgroundFactory.Parse(p.Base, Color.FromRgb(0x22, 0x10, 0x3A)) : null;
	}

	// The most common hue among clearly coloured pixels (value and saturation at least 0.35), averaged; null when
	// fewer than 3 % of the visible pixels are that colourful.
	private static Color? VividColor(BitmapSource src)
	{
		BitmapSource bmp = src.Format == PixelFormats.Bgra32 ? src : new FormatConvertedBitmap(src, PixelFormats.Bgra32, null, 0.0);
		int w = bmp.PixelWidth;
		int h = bmp.PixelHeight;
		if (w < 2 || h < 2)
		{
			return null;
		}
		byte[] px = new byte[w * h * 4];
		bmp.CopyPixels(px, w * 4, 0);
		const int Bins = 24;
		long[] count = new long[Bins];
		long[,] sum = new long[Bins, 3];
		long visible = 0;
		for (int i = 0; i < px.Length; i += 4)
		{
			if (px[i + 3] < 128)
			{
				continue;
			}
			visible++;
			int b = px[i];
			int g = px[i + 1];
			int r = px[i + 2];
			int max = Math.Max(r, Math.Max(g, b));
			int min = Math.Min(r, Math.Min(g, b));
			if (max < 90 || (max - min) < 0.35 * max)
			{
				continue;
			}
			double d = max - min;
			double hue = max == r ? ((g - b) / d) % 6.0 : max == g ? (b - r) / d + 2.0 : (r - g) / d + 4.0;
			if (hue < 0.0)
			{
				hue += 6.0;
			}
			int bin = Math.Min(Bins - 1, (int)(hue / 6.0 * Bins));
			count[bin]++;
			sum[bin, 0] += r;
			sum[bin, 1] += g;
			sum[bin, 2] += b;
		}
		int best = 0;
		for (int i = 1; i < Bins; i++)
		{
			if (count[i] > count[best])
			{
				best = i;
			}
		}
		if (visible == 0 || count[best] * 100 < visible * 3)
		{
			return null;
		}
		long n = count[best];
		return Color.FromRgb((byte)(sum[best, 0] / n), (byte)(sum[best, 1] / n), (byte)(sum[best, 2] / n));
	}

	// Moves a colour's HSL lightness (same hue and saturation) until its relative luminance is inside the tile band.
	internal static Color FitTileLuminance(Color c, Color? background)
	{
		double lo = TileLumMin;
		if (background.HasValue)
		{
			lo = Math.Max(lo, TileBgContrast * (RelativeLuminance(background.Value) + 0.05) - 0.05);
		}
		lo = Math.Min(lo, TileLumMax);
		double l = RelativeLuminance(c);
		if (l >= lo && l <= TileLumMax)
		{
			return c;
		}
		bool raise = l < lo;
		double target = raise ? lo : TileLumMax;
		RgbToHsl(c, out double hue, out double sat, out double light);
		double a = 0.0;
		double z = 1.0;
		for (int i = 0; i < 30; i++)
		{
			double mid = (a + z) / 2.0;
			if (RelativeLuminance(HslToRgb(hue, sat, mid)) < target)
			{
				a = mid;
			}
			else
			{
				z = mid;
			}
		}
		// z is the lightest step at or above the target, a the darkest below it; byte rounding is checked afterwards.
		Color fitted = HslToRgb(hue, sat, raise ? z : a);
		for (int i = 0; i < 8 && (raise ? RelativeLuminance(fitted) < lo : RelativeLuminance(fitted) > TileLumMax); i++)
		{
			light = raise ? Math.Min(1.0, z + 0.004 * (i + 1)) : Math.Max(0.0, a - 0.004 * (i + 1));
			fitted = HslToRgb(hue, sat, light);
		}
		return fitted;
	}

	internal static double RelativeLuminance(Color c)
	{
		static double Lin(byte v)
		{
			double s = v / 255.0;
			return s <= 0.04045 ? s / 12.92 : Math.Pow((s + 0.055) / 1.055, 2.4);
		}
		return 0.2126 * Lin(c.R) + 0.7152 * Lin(c.G) + 0.0722 * Lin(c.B);
	}

	internal static double Contrast(Color a, Color b)
	{
		double la = RelativeLuminance(a);
		double lb = RelativeLuminance(b);
		return (Math.Max(la, lb) + 0.05) / (Math.Min(la, lb) + 0.05);
	}

	private static void RgbToHsl(Color c, out double h, out double s, out double l)
	{
		double r = c.R / 255.0;
		double g = c.G / 255.0;
		double b = c.B / 255.0;
		double max = Math.Max(r, Math.Max(g, b));
		double min = Math.Min(r, Math.Min(g, b));
		l = (max + min) / 2.0;
		double d = max - min;
		if (d < 1e-9)
		{
			h = 0.0;
			s = 0.0;
			return;
		}
		s = l > 0.5 ? d / (2.0 - max - min) : d / (max + min);
		if (max == r)
		{
			h = ((g - b) / d + (g < b ? 6.0 : 0.0)) / 6.0;
		}
		else if (max == g)
		{
			h = ((b - r) / d + 2.0) / 6.0;
		}
		else
		{
			h = ((r - g) / d + 4.0) / 6.0;
		}
	}

	private static Color HslToRgb(double h, double s, double l)
	{
		if (s < 1e-9)
		{
			byte v = (byte)Math.Clamp((int)Math.Round(l * 255.0), 0, 255);
			return Color.FromRgb(v, v, v);
		}
		double q = l < 0.5 ? l * (1.0 + s) : l + s - l * s;
		double p = 2.0 * l - q;
		static double Channel(double p, double q, double t)
		{
			if (t < 0.0)
			{
				t += 1.0;
			}
			if (t > 1.0)
			{
				t -= 1.0;
			}
			if (t < 1.0 / 6.0)
			{
				return p + (q - p) * 6.0 * t;
			}
			if (t < 0.5)
			{
				return q;
			}
			if (t < 2.0 / 3.0)
			{
				return p + (q - p) * (2.0 / 3.0 - t) * 6.0;
			}
			return p;
		}
		static byte B(double v)
		{
			return (byte)Math.Clamp((int)Math.Round(v * 255.0), 0, 255);
		}
		return Color.FromRgb(B(Channel(p, q, h + 1.0 / 3.0)), B(Channel(p, q, h)), B(Channel(p, q, h - 1.0 / 3.0)));
	}

	// ===================================================================== Start entries

	// Shows the seasonal icon on an entry. The first time, what the entry showed is kept in SeasonalUnder so RevertFrom
	// can put exactly those objects back. UI thread.
	internal static void ApplyTo(AppEntry e, string key)
	{
		if (!OnUi(delegate
		{
			ApplyTo(e, key);
		}))
		{
			return;
		}
		ImageSource? icon = Frame(key, Px(112.0 * Math.Max(0.5, TileMetrics.Scale)));
		if (icon == null)
		{
			// The picture cannot be read (any more): the entry shows its own icon, like every other surface does.
			if (e.SeasonalKey != null || e.SeasonalUnder != null)
			{
				RevertFrom(e);
			}
			return;
		}
		Brush brush = TileBrushFor(key);
		if (e.SeasonalKey == key && e.SeasonalUnder != null)
		{
			// Already shown: only pick up new art after the folder changed.
			if (!ReferenceEquals(e.Icon, icon))
			{
				e.Icon = icon;
			}
			if (!ReferenceEquals(e.TileBrush, brush))
			{
				e.TileBrush = brush;
			}
			return;
		}
		e.SeasonalUnder ??= new SeasonalUnder
		{
			Icon = e.Icon,
			TileBrush = e.TileBrush,
			IsOverrideIcon = e.IsOverrideIcon,
			OverrideBrush = e.OverrideBrush
		};
		e.IsOverrideIcon = false;
		e.OverrideBrush = null;
		e.Icon = icon;
		e.TileBrush = brush;
		e.SeasonalKey = key;
	}

	// Puts back exactly what the entry showed before its seasonal icon. UI thread.
	internal static void RevertFrom(AppEntry e)
	{
		if (!OnUi(delegate
		{
			RevertFrom(e);
		}))
		{
			return;
		}
		SeasonalUnder? u = e.SeasonalUnder;
		if (u == null)
		{
			if (e.SeasonalKey != null)
			{
				e.SeasonalKey = null;
			}
			return;
		}
		e.SeasonalKey = null;
		e.Icon = u.Icon;
		e.TileBrush = u.TileBrush;
		e.IsOverrideIcon = u.IsOverrideIcon;
		e.OverrideBrush = u.OverrideBrush;
		e.SeasonalUnder = null;
	}

	private static bool OnUi(Action again)
	{
		Dispatcher? ui = Application.Current?.Dispatcher;
		if (ui == null || ui.CheckAccess())
		{
			return true;
		}
		ui.BeginInvoke(again);
		return false;
	}

	// ===================================================================== helpers

	private static void CountIo()
	{
		Interlocked.Increment(ref _ioCount);
	}

	private static void LogOnce(string id, string line)
	{
		lock (LogGate)
		{
			if (Logged.Count > 512)
			{
				Logged.Clear();
			}
			if (!Logged.Add(id))
			{
				return;
			}
		}
		Write(line);
	}

	private static void Write(string line)
	{
		Logger.Log(line);
		List<string>? qa = QaLog;
		if (qa != null)
		{
			lock (qa)
			{
				qa.Add(line);
			}
		}
	}

	// QA: the files found for a key in the current state, smallest first.
	internal static IReadOnlyList<(int Px, string Path, bool Sized)> QaFrames(string key)
	{
		State s = Current();
		return s.Keys.TryGetValue(key, out FrameFile[]? frames)
			? frames.Select(f => (f.Px, f.Path, f.Sized)).ToList()
			: new List<(int, string, bool)>();
	}

	// QA: forget which messages were logged, so a check can count a message it expects once.
	internal static void QaResetLogOnce()
	{
		lock (LogGate)
		{
			Logged.Clear();
		}
	}
}

// What an entry showed before its seasonal icon; Normal puts exactly these objects back. Loaders that finish while a
// seasonal icon is shown write here instead of on the entry.
internal sealed class SeasonalUnder
{
	public ImageSource? Icon;

	public Brush TileBrush = Brushes.Transparent;

	public bool IsOverrideIcon;

	public Brush? OverrideBrush;
}

// Picks a surface's icon: values = [fallback ImageSource, seasonal key, optional size in DIP]. Without a bound size the
// ConverterParameter (DIP) is used. Returns the seasonal frame at the exact physical size, or the fallback.
public sealed class SeasonalIconConverter : IMultiValueConverter
{
	internal static readonly SeasonalIconConverter Instance = new SeasonalIconConverter();

	// An optional fourth value (a Dark rest flag) shows dark icons the way the black Dark rest surfaces need them
	// (DarkRestIcons.Visible); without it, or with it false, the result is exactly the picked icon. Optional fifth and
	// sixth values (an override's brand brush and the Dark rest tile dimming flag) tone the override art down with its
	// dimmed plate (DarkRestIcons.MutedArt).
	public object? Convert(object[] values, Type targetType, object? parameter, CultureInfo culture)
	{
		object? picked = Pick(values, parameter);
		if (values.Length > 5 && values[5] is true && values[4] is SolidColorBrush brand && values[1] is not string && picked is ImageSource art)
		{
			return DarkRestIcons.MutedArt(art, brand.Color);
		}
		return values.Length > 3 && values[3] is true && picked is ImageSource img ? DarkRestIcons.Visible(img) : picked;
	}

	private static object? Pick(object[] values, object? parameter)
	{
		ImageSource? fallback = values.Length > 0 ? values[0] as ImageSource : null;
		string? key = values.Length > 1 ? values[1] as string : null;
		if (key == null)
		{
			return fallback;
		}
		double dip = 24.0;
		if (values.Length > 2 && values[2] is double bound && bound > 0.0)
		{
			dip = bound;
		}
		else if (parameter is double p && p > 0.0)
		{
			dip = p;
		}
		else if (parameter is string text && double.TryParse(text, NumberStyles.Float, CultureInfo.InvariantCulture, out double parsed) && parsed > 0.0)
		{
			dip = parsed;
		}
		return SeasonalAppIcons.Frame(key, SeasonalAppIcons.Px(dip)) ?? fallback;
	}

	public object[] ConvertBack(object? value, Type[] targetTypes, object? parameter, CultureInfo culture)
	{
		throw new NotSupportedException();
	}
}
